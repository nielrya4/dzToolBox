-- dzToolBox database integrity fix (2026-11-25)
--
-- ROOT CAUSE: both id sequences were defined MAXVALUE 1000 CYCLE. After id 1000 they wrapped
-- back to 1 and handed out ids that real rows already held (user ids wrapped in early Sept,
-- file ids around Nov 8). Combined with the nightly guest cleanup deleting files BY user id,
-- a guest that was issued a real user's id caused that user's projects to be deleted.
-- (This file was already applied to production once as a standalone ALTER; it is idempotent.)
--
-- WHY the rest: production also had no primary keys, no unique constraint on user.username
-- and no foreign key, so the reused ids went unnoticed. New rows reused ids that were already taken. Result: 7 user ids shared by two accounts (so a login
-- could resolve to the wrong person), 1 duplicated code_file id, and 8 duplicated
-- usernames.
--
-- HOW TO RUN (stop the app first, take a provider snapshot/branch too):
--   dry run (default, changes are rolled back):
--     psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f setup/db/2026-11-25_integrity_fix.sql
--   apply for real, after reading the dry-run report:
--     psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -v commit=1 -f setup/db/2026-11-25_integrity_fix.sql
--
-- NOTE: setval()/nextval() are not transactional, so even a dry run moves the sequences
-- forward to max(id). That is harmless (it only skips numbers) and is the desired end state.
--
-- NOTE: existing login sessions and API tokens are tied to user ids. Deploy the new app
-- code (which uses a new SECRET_KEY) together with this script so every old session is
-- invalidated; otherwise someone whose id moved could be logged in as the id's keeper.

BEGIN;
LOCK TABLE "user", code_file IN ACCESS EXCLUSIVE MODE;

-- ---------------------------------------------------------------------------
-- 0. Backups (inside the DB; drop them once you are satisfied. They contain password hashes.)
-- ---------------------------------------------------------------------------
CREATE TABLE backup_user_20261125 AS SELECT u.*, u.ctid::text AS orig_ctid FROM "user" u;
CREATE TABLE backup_code_file_20261125 AS SELECT f.*, f.ctid::text AS orig_ctid FROM code_file f;

-- ---------------------------------------------------------------------------
-- 1. New columns, and allow ids to be rewritten
--    (the id columns are GENERATED ALWAYS identity columns, which cannot be UPDATEd
--    to a specific value; relaxed here, restored to ALWAYS at the end of step 5)
-- ---------------------------------------------------------------------------
ALTER TABLE "user" ALTER COLUMN id SET GENERATED BY DEFAULT;
ALTER TABLE code_file ALTER COLUMN id SET GENERATED BY DEFAULT;

-- Remove the cap: sequences must never wrap (see ROOT CAUSE above).
ALTER TABLE "user" ALTER COLUMN id SET MAXVALUE 2147483647 SET NO CYCLE;
ALTER TABLE code_file ALTER COLUMN id SET MAXVALUE 2147483647 SET NO CYCLE;

ALTER TABLE "user" ADD COLUMN IF NOT EXISTS created_at timestamptz DEFAULT now();  -- NULL for pre-existing rows (unknown)
ALTER TABLE "user" ADD COLUMN IF NOT EXISTS is_guest boolean NOT NULL DEFAULT false;
UPDATE "user" SET is_guest = true WHERE username ~ '^[0-9a-f]{32}_guest$';

-- ---------------------------------------------------------------------------
-- 2. Duplicate usernames (case-insensitive). The account that login currently resolves
--    to (lowest physical position = what `.first()` returned) keeps the name; the others
--    get a '#dupN' suffix. Nothing is deleted. (Checked read-only beforehand: all of these
--    duplicate-name accounts are empty; the only project attached to one of their ids is
--    covered by the id-sharing step below.)
-- ---------------------------------------------------------------------------
CREATE TEMP TABLE username_changes (id int, old_username text, new_username text);

WITH ranked AS (
    SELECT ctid AS row_ctid,
           row_number() OVER (PARTITION BY lower(username) ORDER BY ctid) AS rn
    FROM "user"
), renamed AS (
    UPDATE "user" u
       SET username = u.username || '#dup' || r.rn
      FROM ranked r
     WHERE u.ctid = r.row_ctid AND r.rn > 1
    RETURNING u.id, u.username AS new_username, r.rn
)
INSERT INTO username_changes
SELECT m.id, left(m.new_username, length(m.new_username) - length('#dup' || m.rn)), m.new_username
FROM renamed m;

-- ---------------------------------------------------------------------------
-- 3. Shared user ids. Projects are linked to owners by id ONLY (code_file.user_id), so when
--    two accounts shared an id there is no record of which one really created a project.
--    The account named in keep_owner keeps the id (and the original projects); the other
--    account gets a brand-new id. Where share = true we cannot tell who the owner is, so
--    step 4b gives the other account its own COPY of every project: both users keep their
--    work, nothing is deleted. (Cost: each of the two can see the other's projects.)
--    Where share = false we are confident, and the projects stay only with the keeper.
--
--    Edit the share column to taste. Projects are never deleted, so a wrong choice is fixable.
--      id   keeper                         share  evidence
--       1   Ryan                           false  titles (tensor_test, paper_figs, ...) are Ryan's
--      37   skudaibergen@tamu.edu          false  project is "Ouray Project (Kudaibergenov Shynggys)"
--     110   wangcaiyun                     true   project is "SW Tarim"                  (guess)
--     241   chenshaoyun1998@163.com        true   project "1" from 2025-11-21            (coin flip)
--     242   osinoplu                       true   4 GSA course projects                  (coin flip)
--     322   CadenAnderson                  false  neither account has projects           (irrelevant)
--     528   timothy.campbell2@montana.edu  true   Ouray/Elkhorn/Mercer projects          (guess)
-- ---------------------------------------------------------------------------
SELECT setval(pg_get_serial_sequence('"user"', 'id'), (SELECT max(id) FROM "user"));

CREATE TEMP TABLE keep_owner (id int, username text, share boolean);
INSERT INTO keep_owner VALUES
    (1,   'Ryan',                          false),
    (37,  'skudaibergen@tamu.edu',         false),
    (110, 'wangcaiyun',                    true),
    (241, 'chenshaoyun1998@163.com',       true),
    (242, 'osinoplu',                      true),
    (322, 'CadenAnderson',                 false),
    (528, 'timothy.campbell2@montana.edu', true);

DO $$
DECLARE bad int;
BEGIN
    SELECT count(*) INTO bad
      FROM (SELECT id FROM "user" GROUP BY id HAVING count(*) > 1) d
      LEFT JOIN keep_owner k USING (id)
     WHERE k.id IS NULL;
    IF bad > 0 THEN
        RAISE EXCEPTION 'a shared user id is not covered by keep_owner (% id(s))', bad;
    END IF;

    SELECT count(*) INTO bad FROM keep_owner k
     WHERE (SELECT count(*) FROM "user" u WHERE u.id = k.id AND u.username = k.username) <> 1;
    IF bad > 0 THEN
        RAISE EXCEPTION 'a keep_owner row does not match exactly one account (% row(s))', bad;
    END IF;
END $$;

CREATE TEMP TABLE user_id_changes (old_id int, new_id int, username text, share boolean,
                                   projects_under_old_id bigint, projects_copied bigint DEFAULT 0);

WITH moved AS (
    UPDATE "user" u
       SET id = nextval(pg_get_serial_sequence('"user"', 'id'))
      FROM keep_owner k
     WHERE u.id = k.id AND u.username <> k.username
    RETURNING k.id AS old_id, u.id AS new_id, u.username, k.share
)
INSERT INTO user_id_changes (old_id, new_id, username, share, projects_under_old_id)
SELECT m.old_id, m.new_id, m.username, m.share, (SELECT count(*) FROM code_file f WHERE f.user_id = m.old_id)
FROM moved m;

-- ---------------------------------------------------------------------------
-- 4. Duplicate code_file ids: the older file keeps the id, the newer one gets a new id.
-- ---------------------------------------------------------------------------
SELECT setval(pg_get_serial_sequence('code_file', 'id'), (SELECT max(id) FROM code_file));

CREATE TEMP TABLE file_id_changes (old_id int, new_id int, title text, user_id int);

WITH ranked AS (
    SELECT ctid AS row_ctid,
           row_number() OVER (PARTITION BY id ORDER BY created_at, ctid) AS rn
    FROM code_file
), moved AS (
    UPDATE code_file f
       SET id = nextval(pg_get_serial_sequence('code_file', 'id'))
      FROM ranked r
     WHERE f.ctid = r.row_ctid AND r.rn > 1
    RETURNING f.id AS new_id, f.title, f.user_id
)
INSERT INTO file_id_changes
SELECT NULL, m.new_id, m.title, m.user_id FROM moved m;

-- ---------------------------------------------------------------------------
-- 4b. Where ownership is a toss-up (share = true), give the account that lost the id its own
--     copy of every project stored under that id. Runs after step 4 so the copies get fresh,
--     collision-free ids.
-- ---------------------------------------------------------------------------
CREATE TEMP TABLE expected_copies AS
SELECT count(*)::int AS total
FROM code_file f JOIN user_id_changes c ON c.old_id = f.user_id AND c.share;

WITH copied AS (
    INSERT INTO code_file (title, content, user_id, created_at, updated_at)
    SELECT f.title, f.content, c.new_id, f.created_at, f.updated_at
      FROM code_file f
      JOIN user_id_changes c ON c.old_id = f.user_id AND c.share
    RETURNING user_id
)
UPDATE user_id_changes c
   SET projects_copied = (SELECT count(*) FROM copied WHERE copied.user_id = c.new_id)
 WHERE c.share;

-- ---------------------------------------------------------------------------
-- 5. Constraints
-- ---------------------------------------------------------------------------
ALTER TABLE "user"
    ALTER COLUMN username SET NOT NULL,
    ALTER COLUMN password SET NOT NULL;
ALTER TABLE "user" ADD CONSTRAINT user_pkey PRIMARY KEY (id);
ALTER TABLE "user" ADD CONSTRAINT user_username_key UNIQUE (username);
CREATE UNIQUE INDEX user_username_lower_key ON "user" (lower(username));
DROP INDEX IF EXISTS ix_user_username;  -- redundant with user_username_key

ALTER TABLE code_file
    ALTER COLUMN title SET NOT NULL,
    ALTER COLUMN content SET NOT NULL,
    ALTER COLUMN user_id SET NOT NULL;
ALTER TABLE code_file ADD CONSTRAINT code_file_pkey PRIMARY KEY (id);
ALTER TABLE code_file
    ADD CONSTRAINT code_file_user_id_fkey FOREIGN KEY (user_id) REFERENCES "user" (id) ON DELETE CASCADE;

-- ids are database-assigned only from here on
ALTER TABLE "user" ALTER COLUMN id SET GENERATED ALWAYS;
ALTER TABLE code_file ALTER COLUMN id SET GENERATED ALWAYS;

-- ---------------------------------------------------------------------------
-- 6. Post-conditions (any failure aborts and rolls everything back)
-- ---------------------------------------------------------------------------
DO $$
DECLARE n int;
BEGIN
    IF (SELECT count(*) FROM "user") <> (SELECT count(*) FROM backup_user_20261125) THEN
        RAISE EXCEPTION 'user row count changed';
    END IF;
    IF (SELECT count(*) FROM code_file)
       <> (SELECT count(*) FROM backup_code_file_20261125) + (SELECT total FROM expected_copies) THEN
        RAISE EXCEPTION 'code_file row count is not backup + expected copies';
    END IF;
    IF (SELECT coalesce(sum(projects_copied), 0) FROM user_id_changes) <> (SELECT total FROM expected_copies) THEN
        RAISE EXCEPTION 'copied project count mismatch';
    END IF;
    -- every project must still exist with the same owner, title, timestamp and content
    SELECT count(*) INTO n FROM backup_code_file_20261125 b
     WHERE NOT EXISTS (SELECT 1 FROM code_file f
                        WHERE f.user_id = b.user_id AND f.title = b.title
                          AND f.created_at IS NOT DISTINCT FROM b.created_at
                          AND md5(f.content) = md5(b.content));
    IF n > 0 THEN RAISE EXCEPTION '% project(s) differ from backup', n; END IF;
    IF EXISTS (SELECT 1 FROM pg_sequence WHERE seqcycle OR seqmax < 2147483647) THEN
        RAISE EXCEPTION 'an id sequence is still capped or cycling';
    END IF;
    IF (SELECT last_value FROM user_id_seq) < (SELECT max(id) FROM "user") THEN
        RAISE EXCEPTION 'user_id_seq is behind max(id)';
    END IF;
    IF (SELECT last_value FROM code_file_id_seq) < (SELECT max(id) FROM code_file) THEN
        RAISE EXCEPTION 'code_file_id_seq is behind max(id)';
    END IF;
END $$;

-- ---------------------------------------------------------------------------
-- Report
-- ---------------------------------------------------------------------------
\echo '--- usernames renamed (nothing deleted) ---'
SELECT * FROM username_changes ORDER BY old_username, new_username;
\echo '--- user ids reassigned (the keeper keeps the projects) ---'
SELECT * FROM user_id_changes ORDER BY old_id;
\echo '--- code_file ids reassigned ---'
SELECT * FROM file_id_changes;
\echo '--- constraints ---'
SELECT conrelid::regclass AS tbl, conname, contype FROM pg_constraint
 WHERE conrelid IN ('"user"'::regclass, 'code_file'::regclass) ORDER BY 1, 2;
\echo '--- counts and sequences ---'
SELECT (SELECT count(*) FROM "user") AS users, (SELECT count(*) FROM code_file) AS files,
       (SELECT max(id) FROM "user") AS max_user_id, (SELECT last_value FROM user_id_seq) AS user_seq,
       (SELECT max(id) FROM code_file) AS max_file_id, (SELECT last_value FROM code_file_id_seq) AS file_seq;

\if :{?commit}
    \echo 'COMMITTING'
    COMMIT;
\else
    \echo 'DRY RUN: rolling back. Re-run with -v commit=1 to apply.'
    ROLLBACK;
\endif
